#!/usr/bin/env node
// scripts/media-map-build.js
// Builds design-prototype-v4/media-map.js: an EXPLICIT, deterministic mapping
// from entity ids to existing project assets. The database id is the only
// identity; names/slugs are stored as display labels only.
//
// Re-run after seeding: node scripts/media-map-build.js
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const { Pool } = require('pg');

(async () => {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  const orgs = (await pool.query(
    `SELECT id, slug, type, image, gallery FROM organizations WHERE deleted_at IS NULL`
  )).rows;
  const teachers = (await pool.query(
    `SELECT tp.id, tp.gender, tp.user_id, up.avatar_url
       FROM teacher_profiles tp
       LEFT JOIN user_profiles up ON up.user_id = tp.user_id
      WHERE tp.deleted_at IS NULL`
  )).rows;

  const map = { generatedAt: new Date().toISOString(), organizations: {}, teachers: {}, users: {}, owners: {} };

  orgs.forEach((o) => {
    map.organizations[o.id] = {
      type: o.type || null,
      label: o.slug || null,
      logo: o.image || null,
      cover: null,
      gallery: Array.isArray(o.gallery) ? o.gallery : []
    };
  });
  teachers.forEach((t) => {
    map.teachers[t.id] = {
      gender: t.gender || null,
      userId: t.user_id || null,
      avatar: t.avatar_url || null,
      cover: null,
      gallery: []
    };
  });

  const out =
    '// AUTO-GENERATED by scripts/media-map-build.js — explicit entity id -> existing asset mapping.\n' +
    '// The database id is the entity identity; label/slug is display-only. Do not edit by hand.\n' +
    'window.MADRASATI_MEDIA_MAP = ' + JSON.stringify(map, null, 2) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'design-prototype-v4', 'media-map.js'), out);
  console.log('media-map written: organizations=' + orgs.length + ' teachers=' + teachers.length);
  await pool.end();
})().catch((e) => { console.error('FATAL', e.message); process.exit(1); });
