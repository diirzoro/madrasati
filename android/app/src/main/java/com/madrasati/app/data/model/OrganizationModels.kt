package com.madrasati.app.data.model

import kotlinx.serialization.Serializable

@Serializable
data class Organization(
    val id: String,
    val ownerId: String? = null,
    val name: String? = null,
    val slug: String? = null,
    val type: String? = null,
    val description: String? = null,
    val governorate: String? = null,
    val district: String? = null,
    val governorateCode: String? = null,
    val districtCode: String? = null,
    val neighborhood: String? = null,
    val address: String? = null,
    val phone: String? = null,
    val whatsapp: String? = null,
    val principalName: String? = null,
    val ownerName: String? = null,
    val ownerEmail: String? = null,
    val ownerPhone: String? = null,
    val ownerAvatar: String? = null,
    val email: String? = null,
    val website: String? = null,
    val image: String? = null,
    val gallery: List<String> = emptyList(),
    val facilities: List<String> = emptyList(),
    val offers: List<String> = emptyList(),
    @kotlinx.serialization.SerialName("offersCount") val offersCount: Int? = 0,
    val services: List<String> = emptyList(),
    val discounts: List<String> = emptyList(),
    val activities: List<String> = emptyList(),
    val socialLinks: List<String> = emptyList(),
    val mapUrl: String? = null,
    val registrationStatus: String? = null,
    val registrationInfo: String? = null,
    val bio: String? = null,
    val teachers: Int? = 0,
    val students: Int? = 0,
    @Serializable(with = FlexDoubleSerializer::class) val rating: Double? = 0.0,
    val reviews: Int? = 0,
    val subjects: List<String> = emptyList(),
    val stages: List<String> = emptyList(),
    val languages: List<String> = emptyList(),
    val teachingMethods: List<String> = emptyList(),
    val grades: List<String> = emptyList(),
    val seatsAvailable: Int? = null,
    val registrationOpen: Boolean? = null,
    val gender: String? = null,
    val curriculum: String? = null,
    @Serializable(with = FlexDoubleSerializer::class) val latitude: Double? = null,
    @Serializable(with = FlexDoubleSerializer::class) val longitude: Double? = null,
    val verified: Boolean = false,
    val verificationStatus: String? = "pending",
    val dataSource: String? = "postgres",
    val dataStatus: String? = "active",
    val createdAt: String? = null,
    val updatedAt: String? = null,
)

@Serializable
data class OrganizationListResponse(
    val items: List<Organization> = emptyList(),
    val total: Int = 0,
)
