#!/usr/bin/env node
// db/seed-org-documents.js
//
// Seeds the demo licence/accreditation documents the institution detail screen
// shows. Document *metadata* alone would leave every download 404, so this
// script owns both halves: it writes a small real PDF into
// uploads/org-docs/<organizationId>/ and records the matching row.
//
// Kept out of db/migrations on purpose: migrations are pure SQL and cannot
// write files. Run it after `npm run db:migrate`:
//
//   npm run db:seed:docs
//
// Idempotent: document ids are uuid_generate_v5 over the organization slug and
// doc type, files are overwritten in place, and existing rows are left alone.

require('dotenv').config();
const fs = require('fs');
const path = require('path');
const { Pool } = require('pg');

// Must match modules/documents/service.js, whose UPLOAD_ROOT resolves to
// <project>/server/uploads/org-docs (two levels up from the module directory),
// not <project>/uploads/org-docs.
const UPLOAD_ROOT = path.join(__dirname, '..', 'server', 'uploads', 'org-docs');

const DOC_TYPES = [
  { type: 'license', label: 'License' },
  { type: 'accreditation', label: 'Accreditation' },
];

// Minimal single-page PDF (ASCII only -- embedding an Arabic font would bloat a
// placeholder file, so the body stays Latin while the file NAME stays Arabic).
function buildPdf(lines) {
  const text = lines
    .map((line, i) => `BT /F1 ${i === 0 ? 20 : 12} Tf 60 ${740 - i * 28} Td (${line.replace(/[()\\]/g, '\\$&')}) Tj ET`)
    .join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${Buffer.byteLength(text)} >>\nstream\n${text}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [];
  objects.forEach((body, i) => {
    offsets.push(Buffer.byteLength(pdf));
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefStart = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((off) => {
    pdf += `${String(off).padStart(10, '0')} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  return Buffer.from(pdf, 'latin1');
}

async function main() {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  let files = 0;
  let rows = 0;

  try {
    const { rows: orgs } = await pool.query(
      `SELECT id, name, slug, verified FROM organizations
        WHERE slug IS NOT NULL AND deleted_at IS NULL ORDER BY slug`
    );

    for (const org of orgs) {
      const dir = path.join(UPLOAD_ROOT, org.id);
      fs.mkdirSync(dir, { recursive: true });

      for (const doc of DOC_TYPES) {
        const fileName = `${org.slug}-${doc.type}.pdf`;
        const pdf = buildPdf([
          'Madarasati - Sample Document',
          `Institution: ${org.slug}`,
          `Document type: ${doc.label}`,
          '',
          'Demonstration file generated by db/seed-org-documents.js.',
          'It contains no real licence data.',
        ]);
        fs.writeFileSync(path.join(dir, fileName), pdf);
        files += 1;

        const res = await pool.query(
          `INSERT INTO organization_documents
             (id, organization_id, uploaded_by, doc_type, file_name, file_path,
              mime_type, file_size, status, reviewed_at, review_notes)
           SELECT
             uuid_generate_v5(uuid_ns_url(), 'madrasati:doc:' || $2 || ':' || $3),
             $1, NULL, $3, $4, $5, 'application/pdf', $6, $7,
             CASE WHEN $7 = 'verified' THEN now() ELSE NULL END,
             CASE WHEN $7 = 'verified' THEN 'Seeded demo document.' ELSE NULL END
           ON CONFLICT (id) DO NOTHING`,
          [
            org.id,
            org.slug,
            doc.type,
            `${org.name} - ${doc.label}.pdf`,
            `${org.id}/${fileName}`,
            pdf.length,
            org.verified ? 'verified' : 'pending',
          ]
        );
        rows += res.rowCount;
      }
    }

    console.log(`  organizations: ${orgs.length} | files written: ${files} | rows inserted: ${rows}`);
  } finally {
    await pool.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
